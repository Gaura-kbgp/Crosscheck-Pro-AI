"""
Phase 1 — Finish Normalization Tests.

Covers:
  1. are_finishes_equivalent unit tests (12 cases)
  2. Regression: different cabinet styles/colors are NOT merged
  3. MCV144 integration test: abbreviated "DEWDROP" == full "JAMESTOWN PHW DEWDROP"
     → no finish discrepancy generated by CrossCheckEngine
"""
import pytest
from uuid import uuid4

from app.engines.normalization import are_finishes_equivalent
from app.engines.crosscheck import CrossCheckEngine
from app.models.core import (
    CanonicalLineItem, DocumentType, MatchGroup, MatchGroupStatus,
)


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _item(source_type, sku, finish=None, qty=1):
    return CanonicalLineItem(
        id=uuid4(),
        project_id=uuid4(),
        organization_id=uuid4(),
        source_type=source_type,
        raw_sku=sku,
        normalized_sku=sku,
        quantity=qty,
        finish=finish,
    )


def _mg(d=None, o=None, a=None):
    proj_id = uuid4()
    org_id = uuid4()
    return MatchGroup(
        id=uuid4(),
        project_id=proj_id,
        organization_id=org_id,
        status=MatchGroupStatus.CHANGED,
        design_item_id=d.id if d else None,
        order_item_id=o.id if o else None,
        ack_item_id=a.id if a else None,
        design_item=d,
        order_item=o,
        ack_item=a,
    )


# ---------------------------------------------------------------------------
# 1. Unit tests for are_finishes_equivalent
# ---------------------------------------------------------------------------

def test_verified_alias_abbreviated_vs_full():
    assert are_finishes_equivalent("DEWDROP", "JAMESTOWN PHW DEWDROP") is True

def test_verified_alias_full_ply_vs_abbreviated():
    assert are_finishes_equivalent("JAMESTOWN PHW DEWDROP PLY B", "DEWDROP") is True

def test_verified_alias_cocoa():
    assert are_finishes_equivalent("COCOA", "ATLANTA BIRCH COCOA") is True

def test_verified_alias_jute_fx():
    assert are_finishes_equivalent("JUTE", "APEX OAK JUTE FX") is True

def test_verified_alias_sagewood():
    assert are_finishes_equivalent("SAGEWOOD", "MONROE PHW SAGEWOOD PLY") is True

def test_case_insensitive_lookup():
    # normalize_text uppercases — "dewdrop" should map to canonical DEWDROP
    assert are_finishes_equivalent("dewdrop", "JAMESTOWN PHW DEWDROP") is True

def test_unknown_finish_exact_match():
    assert are_finishes_equivalent("CUSTOM TEAL", "CUSTOM TEAL") is True

def test_unknown_finish_no_match():
    assert are_finishes_equivalent("CUSTOM TEAL", "CUSTOM NAVY") is False

def test_none_input_returns_false():
    assert are_finishes_equivalent(None, "DEWDROP") is False
    assert are_finishes_equivalent("DEWDROP", None) is False
    assert are_finishes_equivalent(None, None) is False

def test_empty_string_returns_false():
    assert are_finishes_equivalent("", "DEWDROP") is False


# ---------------------------------------------------------------------------
# 2. Regression: different styles/colors must NOT be merged
# ---------------------------------------------------------------------------

def test_different_colors_not_equivalent():
    """DEWDROP and ALPINE are different colors — must never match."""
    assert are_finishes_equivalent("DEWDROP", "ALPINE") is False

def test_different_colors_full_form_not_equivalent():
    """Full-form finishes for different colors must not merge."""
    assert are_finishes_equivalent("JAMESTOWN PHW DEWDROP", "MONROE PHW SAGEWOOD") is False

def test_different_colors_mixed_form_not_equivalent():
    assert are_finishes_equivalent("DEWDROP", "MONROE PHW SAGEWOOD") is False
    assert are_finishes_equivalent("JAMESTOWN PHW DEWDROP", "SAGEWOOD") is False

def test_crosscheck_different_colors_generates_discrepancy():
    """Different finishes (DEWDROP vs ALPINE) must still produce a finish discrepancy."""
    proj_id = uuid4()
    org_id = uuid4()
    d = _item(DocumentType.DESIGN, "B30", finish="DEWDROP")
    o = _item(DocumentType.ORDER, "B30", finish="ALPINE")
    a = _item(DocumentType.ACKNOWLEDGEMENT, "B30", finish="ALPINE")
    mg = _mg(d, o, a)

    discs = CrossCheckEngine().evaluate([mg], proj_id, org_id)
    finish_discs = [x for x in discs if x.field == "finish"]
    assert len(finish_discs) >= 1, "Different colors must produce a finish discrepancy"


# ---------------------------------------------------------------------------
# 3. MCV144 integration test — the primary acceptance gate for Phase 1
# ---------------------------------------------------------------------------

def test_mcv144_abbreviated_vs_full_finish_no_discrepancy():
    """
    MCV144: DESIGN finish="DEWDROP", ORDER finish="JAMESTOWN PHW DEWDROP".
    These refer to the same color — CrossCheckEngine must NOT generate a
    finish discrepancy.
    """
    proj_id = uuid4()
    org_id = uuid4()

    d = _item(DocumentType.DESIGN,          "MCV144", finish="DEWDROP",               qty=1)
    o = _item(DocumentType.ORDER,           "MCV144", finish="JAMESTOWN PHW DEWDROP",  qty=1)
    a = _item(DocumentType.ACKNOWLEDGEMENT, "MCV144", finish="JAMESTOWN PHW DEWDROP",  qty=1)
    mg = _mg(d, o, a)

    discs = CrossCheckEngine().evaluate([mg], proj_id, org_id)
    finish_discs = [x for x in discs if x.field == "finish"]
    assert finish_discs == [], (
        f"MCV144 abbreviated vs full finish should not produce a discrepancy; got: {finish_discs}"
    )

def test_mcv144_both_abbreviated_no_discrepancy():
    """When both sides use abbreviated finish, no discrepancy expected."""
    proj_id = uuid4()
    org_id = uuid4()
    d = _item(DocumentType.DESIGN,          "MCV144", finish="DEWDROP", qty=1)
    o = _item(DocumentType.ORDER,           "MCV144", finish="DEWDROP", qty=1)
    a = _item(DocumentType.ACKNOWLEDGEMENT, "MCV144", finish="DEWDROP", qty=1)
    mg = _mg(d, o, a)
    discs = CrossCheckEngine().evaluate([mg], proj_id, org_id)
    assert not any(x.field == "finish" for x in discs)

def test_mcv144_genuine_finish_discrepancy_still_surfaces():
    """MCV144 with actually different finishes must still produce a discrepancy."""
    proj_id = uuid4()
    org_id = uuid4()
    d = _item(DocumentType.DESIGN,          "MCV144", finish="DEWDROP", qty=1)
    o = _item(DocumentType.ORDER,           "MCV144", finish="ALPINE",  qty=1)
    a = _item(DocumentType.ACKNOWLEDGEMENT, "MCV144", finish="ALPINE",  qty=1)
    mg = _mg(d, o, a)
    discs = CrossCheckEngine().evaluate([mg], proj_id, org_id)
    finish_discs = [x for x in discs if x.field == "finish"]
    assert len(finish_discs) >= 1, "Genuinely different finishes must still produce a discrepancy"
